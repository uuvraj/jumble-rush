/**
 * Scrambles a word randomly and guarantees the scrambled output
 * does NOT match the original word.
 */
export function scrambleWord(word) {
  const clean = word.toUpperCase().trim();
  if (clean.length <= 1) return clean;

  const letters = clean.split('');
  let scrambled = clean;
  let attempts = 0;
  const maxAttempts = 100;

  // Try random permutations
  while (scrambled === clean && attempts < maxAttempts) {
    const arr = [...letters];
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    scrambled = arr.join('');
    attempts++;
  }

  // If still matches (e.g. words with duplicate letters that happen to match),
  // force swap between two distinct characters if available
  if (scrambled === clean) {
    const arr = [...letters];
    for (let i = 0; i < arr.length - 1; i++) {
      for (let j = i + 1; j < arr.length; j++) {
        if (arr[i] !== arr[j]) {
          [arr[i], arr[j]] = [arr[j], arr[i]];
          scrambled = arr.join('');
          return scrambled;
        }
      }
    }
  }

  return scrambled;
}
